const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
const login = read('supabase/functions/veresiye-portal-login/index.ts');
const crypto = read('supabase/functions/veresiye-portal-login/_shared/crypto.ts');
const app = read('src/App.tsx');
const client = read('src/lib/veresiye.ts');
assert.match(crypto, /signCustomerSessionToken/);
assert.match(crypto, /verifyCustomerSessionToken/);
assert.match(crypto, /customer-session/);
assert.match(login, /session_token\?: string/);
assert.match(login, /\.eq\('customer_id', payload\.customer_id\)/);
assert.match(login, /\.eq\('is_active', true\)/);
assert.match(login, /session_token: newSessionToken/);
assert.match(app, /CUSTOMER_SESSION_KEY/);
assert.match(app, /localStorage\.setItem\(CUSTOMER_SESSION_KEY, result\.sessionToken\)/);
assert.match(app, /localStorage\.removeItem\(CUSTOMER_SESSION_KEY\)/);
assert.match(app, /Beni hatırla/);
assert.match(client, /resumeCustomerSession/);
assert.doesNotMatch(app, /login-customer-guide|Hangi kodu girmeliyim/);
assert.doesNotMatch(app, /localStorage\.setItem\([^,]*,\s*code\s*\)/);
console.log('PASS: remembered customer sessions use signed 30-day tokens, re-check account access, clear on logout, and never persist the six-digit code.');
